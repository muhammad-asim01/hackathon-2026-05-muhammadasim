// ─── Lead types ──────────────────────────────────────────────────────────────

export type LeadStatus = "new" | "contacted" | "approved" | "rejected" | "cold";

export type ReviewSentiment = "positive" | "mixed" | "negative";

export interface Lead {
  id: string;
  businessName: string;
  address: string;
  city: string;
  niche: string;
  phone: string;
  website: string;
  googleRating: number;
  reviewCount: number;
  /** 0–75 — leads scoring > 75 are filtered out before storage */
  digitalScore: number;
  pageSpeedScore: number;
  mobileScore: number;
  reviewSentiment: ReviewSentiment;
  status: LeadStatus;
  emailDraftId: string | null;
  discoveredAt: string; // ISO
  runId: string;
  topIssue: string;
  reviewExcerpt: string;
}

// ─── Score helpers ────────────────────────────────────────────────────────────

/** Returns ShadCN Badge variant based on digital score */
export function scoreVariant(
  score: number
): "error" | "warning" | "success" | "muted" {
  if (score <= 55) return "error";
  if (score <= 75) return "warning";
  return "success"; // shouldn't appear — filtered upstream
}

/** Returns a human-readable label for the score tier */
export function scoreTier(score: number): string {
  if (score <= 55) return "Immediate outreach";
  if (score <= 75) return "Audit offer";
  return "Skip";
}

